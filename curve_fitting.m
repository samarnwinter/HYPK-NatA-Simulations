% =====Normalized Elongation Rate (k3) vs Nascent Chain Length =====

% ===================Experimental data ============================

NC_length = [68, 88, 95, 105, 115, 135, 155, 185, 205];
Avg_k = [0, 0.001373, 0.002281, 0.845, 0.2825, 0.17, 0.285, 0.075, 0.046];

% Gaussian fit parameters 

a1 = 0.79;     b1 = 105.0;   c1 = 6.414;
a2 = 0.20;     b2 = 116.2;   c2 = 10.6473;
a3 = 0.2950;   b3 = 154.5404; c3 = 28.1588;

x = 1:1:350;

Y = a1 * exp(-((x - b1) ./ c1).^2) + ...
    a2 * exp(-((x - b2) ./ c2).^2) + ...
    a3 * exp(-((x - b3) ./ c3).^2);

Avg_k_normalized = Avg_k;

T = table(x', Y', 'VariableNames', {'Nc_length', 'k3'});
writetable(T, "curve_fit_k3.xlsx");

%%%%%%%%%%%%%%%

figure('Color','w','Units','centimeters','Position',[5,5,16,10]);
hold on

scatter(NC_length, Avg_k_normalized, 55, ...
    'MarkerFaceColor',[0.15 0.45 0.80], ...
    'MarkerEdgeColor',[0.1 0.1 0.1], ...
    'LineWidth',0.6, ...
    'DisplayName','Experimental data');

plot(x, Y, 'LineWidth',2.2, ...
    'Color',[0.80 0.25 0.15],'DisplayName','Fitted func' );

xlabel('Nascent chain length (aa)', 'FontName','Helvetica', 'FontSize',14);
ylabel('k3', 'FontName','Helvetica', 'FontSize',14);

set(gca, ...
    'FontName','Helvetica', ...
    'FontSize',10, ...
    'LineWidth',0.8, ...
    'Box','off', ...
    'TickDir','out', ...
    'XMinorTick','on', ...
    'YMinorTick','on', ...
    'TickLength',[0.015 0.015], ...
    'XColor',[0.2 0.2 0.2], ...
    'YColor',[0.2 0.2 0.2], ...
    'XLim',[50 210], ...
    'YLim',[-0.05 0.9], ...
    'XGrid','on', ...
    'YGrid','on', ...
    'GridLineStyle',':', ...
    'GridAlpha',0.25);

L = legend('show', 'Location','northeast');
set(L, 'Box','off', 'FontSize',9, 'FontName','Helvetica');


